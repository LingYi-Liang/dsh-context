import assert from 'node:assert/strict'
import { describe, test } from 'vitest'
import { createSessionRowEmitter } from '../../../src/host/store/emitter'

function emitter(): ReturnType<typeof createSessionRowEmitter> {
  return createSessionRowEmitter({ sessionId: 's1' })
}

describe('session row emitter — direct branch coverage', () => {
  test('surface rows carry every optional field and capped previews', () => {
    const sink = emitter()
    sink.surface({ seq: 1, time: 5, cat: 'assistant', tokens: 9, reasoning: 2, answerTokens: 3, callTokens: 4, imgs: 1, form: 'form-x', name: 'n', agent: 'a', tool: 't', skill: 'sk', err: true, calls: ['bash'], text: 'p'.repeat(3_000) })
    sink.surface({ seq: 2, cat: 'user', tokens: 1 })
    const ops = sink.takeOps()
    const full = ops[0].patch
    assert.equal(full.reasoning_tokens, 2)
    assert.equal(full.answer_tokens, 3)
    assert.equal(full.call_tokens, 4)
    assert.equal(full.imgs, 1)
    assert.equal(full.form, 'form-x')
    assert.equal(full.agent, 'a')
    assert.equal(full.is_error, 1)
    assert.equal(full.calls, '["bash"]')
    assert.equal((full.preview as string).length, 2_000)
    assert.equal(ops[1].patch.preview, null)
    assert.equal(ops[1].patch.time, null)
    assert.equal(ops[1].patch.calls, null)
  })

  test('request rows map usage buckets, period and null components', () => {
    const sink = emitter()
    sink.request({ seq: 1, time: 10, turn: 1, step: 0, day: '2026-11-15', startsTurn: true, system: 1, tools: 2, user: 3, inject: 0, skill: 0, assistant: 4, tool: 5, total: 15, model: 'm', provider: 'deepseek', period: 'off', usage: { prompt: 10, input: 4, cacheRead: 6, cacheWrite: null, output: 5, reasoning: 2 }, genMs: 30 })
    sink.request({ seq: 2, time: 20, day: null, startsTurn: false, system: 0, tools: 0, user: 0, inject: 0, skill: 0, assistant: 0, tool: 0, total: 0, period: null, usage: null })
    const ops = sink.takeOps()
    assert.equal(ops[0].patch.input_tokens, 4)
    assert.equal(ops[0].patch.cache_write_tokens, null)
    assert.equal(ops[0].patch.reasoning_tokens, 2)
    assert.equal(ops[0].patch.gen_ms, 30)
    assert.equal(ops[1].patch.input_tokens, null)
    assert.equal(ops[1].patch.model, null)
    assert.equal(ops[1].patch.period, null)
    assert.equal(ops[1].patch.period, null)
  })

  test('tool call rows cover command records, plain tools and every patch branch', () => {
    const sink = emitter()
    sink.toolCall({ seq: 1, callId: 'c1', name: 'bash', start: 100, arguments: '{"command":"ls -la"}', record: { seq: 1, time: 100, tool: 'bash', cmd: 'ls -la', description: 'list', cwd: '/w', timeoutMs: 5_000, background: true, sandbox: 'strict', turn: 1, step: 2, start: 100, status: 'running', err: false, call: 'c1' } })
    sink.toolCall({ seq: 2, callId: 'c2', name: 'read', start: 200 })
    sink.toolCallPatch('c1', { resultSeq: 3, end: 150, durationMs: 50, isError: true, rec: { seq: 1, time: 100, tool: 'bash', cmd: 'ls -la', start: 100, status: 'failed', err: true, exit: 2, exitInferred: true, signal: 'SIGKILL', timedOut: true, stopped: true, denied: true, background: true, derived: true, outChars: 9, outTruncated: true, stderr: true, call: 'c1', cwd: '/new' } })
    sink.toolCallPatch('c2', { resultSeq: 4, end: 250, durationMs: 50, isError: false, transport: true })
    sink.toolCallPatch('c-missing', { resultSeq: 9, end: 9, durationMs: 9, isError: true })
    const ops = sink.takeOps()
    const bash = ops[0].patch
    assert.equal(bash.program, 'ls')
    assert.equal(bash.plugin, null)
    assert.equal(bash.timeout_ms, 5_000)
    assert.equal(bash.sandbox, 'strict')
    assert.equal(bash.background, 1)
    assert.equal(bash.cmd_description, 'list')
    assert.equal(bash.cmd_cwd, '/w')
    assert.equal(bash.turn, 1)
    assert.equal(bash.day, bash.day)
    const plain = ops[1].patch
    assert.equal(plain.record === undefined ? plain.status : plain.status, 'running')
    const patch1 = ops[2]
    assert.equal(patch1.update, 'seq')
    assert.equal(patch1.patch.exit_code, 2)
    assert.equal(patch1.patch.exit_inferred, 1)
    assert.equal(patch1.patch.signal, 'SIGKILL')
    assert.equal(patch1.patch.timed_out, 1)
    assert.equal(patch1.patch.stopped, 1)
    assert.equal(patch1.patch.denied, 1)
    assert.equal(patch1.patch.derived, 1)
    assert.equal(patch1.patch.out_chars, 9)
    assert.equal(patch1.patch.out_truncated, 1)
    assert.equal(patch1.patch.stderr, 1)
    assert.equal(patch1.patch.cmd_cwd, '/new')
    const patch2 = ops[3]
    assert.equal(patch2.update, 'seq')
    assert.equal(patch2.patch.transport, 1)
    assert.equal(patch2.patch.is_error, 0)
    const missing = ops[4]
    assert.equal(missing.update, 'call_id')
    assert.equal(missing.patch.call_id, 'c-missing')
  })

  test('transport parent patches resolve through the pairing map', () => {
    const sink = emitter()
    sink.toolCall({ seq: 7, callId: 'root', name: 'run_code', start: 1 })
    sink.toolCallPatch('root', { transport: true })
    const ops = sink.takeOps()
    assert.equal(ops.length, 2)
    assert.equal(ops[1].update, 'seq')
    assert.equal(ops[1].patch.seq, 7)
    assert.equal(ops[1].patch.transport, 1)
  })

  test('events, system prompts, epochs, file ops, skill loads, spans and cuts', () => {
    const sink = emitter()
    sink.event({ seq: 1, time: 2, kind: 'inject', sub: 'skill', form: 'instructions', name: 'sk', agent: 'agent-x', detail: 'd'.repeat(300), tokens: 9, grossTokens: 3, count: 4, from: 'a', to: 'b' })
    sink.event({ seq: 2, time: 3, kind: 'mode' })
    sink.eventShadowUpdate(1, 7, 12)
    sink.systemPrompt(5, 6, 100)
    sink.systemPromptsDropped([5, 6])
    sink.headerEpoch(7, 8, 90, 'change')
    sink.headerEpoch(8, 9, 0, 42)
    sink.headerTools(7, [{ name: 'bash', plugin: 'p' }, { name: '' }, null, 'junk'])
    sink.fileOps([
      { seq: 10, kind: 'read', tool: 'read', path: '/a', err: false, added: 0, removed: 0, read: { start: 3, count: 9 } },
      { seq: 10, kind: 'search', tool: 'grep', path: '/b', err: true, added: 2, removed: 1, detail: 'd'.repeat(400), hits: 5, pattern: true, parent: 9, program: 'prog' },
      { seq: 11, kind: 'write', tool: 'write', path: '/c', err: false, added: 1, removed: 0, read: { count: 4, est: true } },
    ])
    sink.skillLoad(12, 13, 'sk', 'result')
    sink.spans([{ kind: 'ttft', start: 1, end: 2 }, { kind: 'tools', start: 2, end: 3 }])
    sink.inheritedCut(99)
    const ops = sink.takeOps()
    const eventRows = ops.filter(op => op.table === 'events' && op.update === undefined)
    assert.equal(eventRows.length, 2)
    assert.equal(eventRows[0].patch.detail, 'd'.repeat(200))
    assert.equal(eventRows[0].patch.node_count, 4)
    assert.equal(eventRows[0].patch.model_from, 'a')
    assert.equal(eventRows[1].patch.detail, null)
    const shadow = ops.find(op => op.table === 'events' && op.update === 'seq')
    assert.equal(shadow?.patch.tokens, 7)
    assert.equal(shadow?.patch.gross_tokens, 12)
    const deletes = ops.filter(op => op.delete === true)
    assert.equal(deletes.length, 2)
    assert.deepEqual(deletes.map(op => op.patch.seq), [5, 6])
    const epoch = ops.find(op => op.table === 'header_epochs')
    assert.equal(epoch?.patch.reason, 'change')
    const epoch2 = ops.filter(op => op.table === 'header_epochs')[1]
    assert.equal(epoch2?.patch.reason, null)
    const tools = ops.filter(op => op.table === 'header_tools')
    assert.equal(tools.length, 2)
    assert.equal(tools[0].patch.plugin, 'p')
    assert.equal(tools[1].patch.name, '?')
    
    const fileRows = ops.filter(op => op.table === 'file_ops')
    assert.equal(fileRows.length, 3)
    assert.equal(fileRows[0].patch.read_start, 3)
    assert.equal(fileRows[0].patch.read_est, 0)
    assert.equal(fileRows[1].patch.ordinal, 1)
    assert.equal(fileRows[1].patch.detail, 'd'.repeat(200))
    assert.equal(fileRows[1].patch.is_pattern, 1)
    assert.equal(fileRows[1].patch.parent_seq, 9)
    assert.equal(fileRows[1].patch.program, 'prog')
    assert.equal(fileRows[2].patch.read_start, null)
    assert.equal(fileRows[2].patch.read_est, 1)
    assert.equal(fileRows[2].patch.ordinal, 0)
    const skill = ops.find(op => op.table === 'skill_loads')
    assert.equal(skill?.patch.source, 'result')
    const spans = ops.filter(op => op.table === 'timing_spans')
    assert.deepEqual(spans.map(op => op.patch.span_seq), [0, 1])
    assert.equal(sink.takeInheritedCut(), 99)
    assert.equal(sink.takeInheritedCut(), null)
    assert.equal(sink.takeOps().length, 0)
  })

  test('empty patches are dropped instead of writing no-op updates', () => {
    const sink = emitter()
    sink.toolCallPatch('c1', {})
    assert.equal(sink.takeOps().length, 0)
  })
})
